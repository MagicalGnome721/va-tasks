#!/usr/bin/env python3
"""Assemble index.html, Code.gs, appsscript.json in the PROJECT ROOT from src parts.
Run from anywhere: python3 -I src/build.py
Never edit the generated files directly - edit src/ and rebuild."""
import os, shutil
SRC = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.dirname(SRC)
rd = lambda n: open(os.path.join(SRC, n), encoding='utf-8').read()
STAMP_JS = "// GENERATED from src/ by build.py - do not edit this file, edit src/ and rebuild.\n"

rules = rd('rules.js')
import base64, json
def data_uri(n, mime):
    with open(os.path.join(SRC, 'assets', n), 'rb') as f: return 'data:' + mime + ';base64,' + base64.b64encode(f.read()).decode()
ASSETS = {'mascotWave': data_uri('mascot-wave.webp', 'image/webp'), 'mascotSmile': data_uri('mascot-smile.webp', 'image/webp'),
          'mascotTired': data_uri('mascot-tired.webp', 'image/webp'), 'mascotSnack': data_uri('mascot-snack.webp', 'image/webp'),
          'teamBadge': data_uri('team-badge.webp', 'image/webp')}
FAVICON = data_uri('favicon.png', 'image/png')
# meme của Cún: src/assets/memes/<cảm xúc>/*.webp|png|jpg — tên thư mục phải khớp Rules.BUDDY_MOODS trong rules.js
MEME_DIR = os.path.join(SRC, 'assets', 'memes'); MIME = {'.webp': 'image/webp', '.png': 'image/png', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg'}
ASSETS['memes'] = {}
if os.path.isdir(MEME_DIR):
    for mood in sorted(os.listdir(MEME_DIR)):
        d = os.path.join(MEME_DIR, mood)
        if not os.path.isdir(d): continue
        files = [f for f in sorted(os.listdir(d)) if os.path.splitext(f)[1].lower() in MIME]
        ASSETS['memes'][mood] = [data_uri(os.path.join('memes', mood, f), MIME[os.path.splitext(f)[1].lower()]) for f in files]
    print('memes:', {k: len(v) for k, v in ASSETS['memes'].items()})
app = "(function () {\n'use strict';\nconst ASSETS = " + json.dumps(ASSETS) + ";\n" + "\n".join(rd(n) for n in ['app-core.js', 'app-ops.js', 'app-views.js', 'app-ai.js', 'buddy-lines.js', 'app-buddy.js', 'app-main.js']) + "\n})();\n"
shell = rd('shell.html')
assert '/*__RULES__*/' in shell and '/*__APP__*/' in shell, 'shell.html placeholders missing'
html = shell.replace('__FAVICON__', FAVICON).replace('__TEAM_BADGE__', ASSETS['teamBadge']).replace('/*__RULES__*/', rules).replace('/*__APP__*/', app)
# stamp goes AFTER the doctype: a comment before <!doctype> would force quirks mode
first_nl = html.index('\n') + 1
html = html[:first_nl] + "<!-- GENERATED from src/ by build.py - do not edit this file, edit src/ and rebuild. -->\n" + html[first_nl:]
# index.html = bản dev/test (có Demo). publish/index.html = bản phát hành gắn máy chủ trong src/deploy.json.
with open(os.path.join(OUT, 'index.html'), 'w', encoding='utf-8', newline='\n') as f: f.write(html.replace('__BUILT_API__', ''))
dep = os.path.join(SRC, 'deploy.json')
if os.path.exists(dep):
    api = json.load(open(dep, encoding='utf-8')).get('apiUrl', '').strip()
    assert api.startswith('https://script.google.com/macros/s/') and api.endswith('/exec') and "'" not in api, 'deploy.json apiUrl invalid'
    os.makedirs(os.path.join(OUT, 'publish'), exist_ok=True)
    with open(os.path.join(OUT, 'publish', 'index.html'), 'w', encoding='utf-8', newline='\n') as f: f.write(html.replace('__BUILT_API__', api))
    open(os.path.join(OUT, 'publish', '.nojekyll'), 'w').close()
    print('publish/index.html ->', api)

gs = STAMP_JS + rd('code-head.gs') + "\n" + rules + "\n" + rd('code-main.gs')
with open(os.path.join(OUT, 'Code.gs'), 'w', encoding='utf-8', newline='\n') as f: f.write(gs)
shutil.copy(os.path.join(SRC, 'appsscript.json'), os.path.join(OUT, 'appsscript.json'))
print('built', len(html), 'bytes html,', len(gs), 'bytes gs ->', OUT)
